use expression::{Expr, expected};
fn check<const OP:usize,const M:usize,const K:usize,const N:usize>() {
 let a=tensor::Tensor::from_vec(vec![M,K],(0..M*K).map(Expr::leaf).collect()).unwrap();
 let (br,bc)=if OP==4 {(K,N)} else {(M,K)};
 let b=tensor::Tensor::from_vec(vec![br,bc],(0..br*bc).map(|i|Expr::leaf(i+16)).collect()).unwrap();
 let out=match OP {
  0=>a.clone(),1=>a.zip(&b,|x,y|x+y).unwrap(),2=>a.zip(&b,|x,y|x*y).unwrap(),
  3=>a.permute(&[1,0]).unwrap(),4=>a.matmul(&b).unwrap(),5=>a.map(|x|Expr::leaf(16)*x),
  _=>unreachable!(),
 };
 let (rows,cols)=if OP==3 {(K,M)} else if OP==4 {(M,N)} else {(M,K)};
 assert_eq!(out.shape(),&[rows,cols]); assert_eq!(out.strides(),&[cols,1]);
 for r in 0..rows {for c in 0..cols {
  assert_eq!(*out.get(&[r,c]).unwrap(),expected(OP,M,K,N,r,c),"ordered expression matches specification");
 }}
 for i in 0..M*K {assert_eq!(a.as_slice()[i],Expr::leaf(i),"first input unchanged");}
 for i in 0..br*bc {assert_eq!(b.as_slice()[i],Expr::leaf(i+16),"second input unchanged");}
}
